#!/bin/bash

# MacPatch Agent Uploader Builder
# Builds MPAgentUploader.app with xcodebuild, then (optionally) signs it with a
# Developer ID Application certificate, notarizes it, and staples the ticket.
# Output is a .app and a distributable .zip (no Apple pkg).

set -e
set -o pipefail

SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
BUILD_DIR="$SCRIPT_DIR/build"
DERIVED_DIR="$BUILD_DIR/DerivedData"
PROJECT="MPAgentUploader.xcodeproj"
SCHEME="MPAgentUploader"
APP_NAME="MPAgentUploader"
BUILT_APP="$DERIVED_DIR/Build/Products/Release/$APP_NAME.app"
CONFIG_FILE="$HOME/Library/Preferences/com.llnl.mp.agentuploader.build_config"

echo "╔════════════════════════════════════════════════╗"
echo "║   MacPatch Agent Uploader Builder              ║"
echo "╚════════════════════════════════════════════════╝"
echo

# Load previous configuration if it exists
if [ -f "$CONFIG_FILE" ]; then
    source "$CONFIG_FILE"
    echo "  ✓ Loaded configuration from previous build"
    echo
fi

prompt_with_default() {
    local prompt="$1"
    local default="$2"
    local result

    read -p "${prompt} [${default}]: " result
    echo "${result:-$default}"
}

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------
echo "Signing & Notarization"
echo "────────────────────────────────────────────────"
echo

DEFAULT_NOTARIZE="Y"
if [[ "$SAVED_DO_NOTARIZE" =~ ^[Nn]$ ]]; then
    DEFAULT_NOTARIZE="N"
fi

read -p "Sign and notarize app? [Y/n]: " DO_NOTARIZE
DO_NOTARIZE=${DO_NOTARIZE:-$DEFAULT_NOTARIZE}

if [[ "$DO_NOTARIZE" =~ ^[Yy]$ ]]; then
    echo
    echo "Available Developer ID Application certificates:"
    security find-identity -p basic -v | grep "Developer ID Application" | sed 's/^[[:space:]]*[0-9]*)/  -/' || true
    echo
    SIGN_APP_IDENTITY=$(prompt_with_default "Developer ID Application identity" "${SAVED_SIGN_APP_IDENTITY:-}")
    while [ -z "$SIGN_APP_IDENTITY" ]; do
        echo "Identity cannot be empty when signing is enabled"
        SIGN_APP_IDENTITY=$(prompt_with_default "Developer ID Application identity" "")
    done

    echo
    echo "Notarization uses a keychain profile stored with 'notarytool store-credentials'."
    echo "If you haven't created one yet, run:"
    echo "  xcrun notarytool store-credentials <profile-name> --apple-id <email> --team-id <team>"
    echo "Or with API key:"
    echo "  xcrun notarytool store-credentials <profile-name> --key <key.p8> --key-id <id> --issuer <issuer>"
    echo

    KEYCHAIN_PROFILE=$(prompt_with_default "Keychain profile name" "${SAVED_KEYCHAIN_PROFILE:-AC_NOTARY}")
else
    SIGN_APP_IDENTITY=""
    KEYCHAIN_PROFILE=""
fi

echo
echo "Build Summary:"
echo "  Project:          $PROJECT ($SCHEME, Release)"
if [ -n "$SIGN_APP_IDENTITY" ]; then
    echo "  App Identity:     $SIGN_APP_IDENTITY"
    echo "  Keychain Profile: $KEYCHAIN_PROFILE"
else
    echo "  Signing:          Disabled (development build)"
fi
echo

read -p "Proceed with build? [Y/n]: " CONFIRM
if [[ ! "$CONFIRM" =~ ^[Yy]?$ ]]; then
    echo "Build cancelled."
    exit 0
fi

# Save configuration early so it's preserved even if the build fails
cat > "$CONFIG_FILE" << CONFIGEOF
# Build configuration saved on $(date)
# This file is automatically generated and loaded by build_app.sh
SAVED_DO_NOTARIZE="$DO_NOTARIZE"
SAVED_SIGN_APP_IDENTITY="$SIGN_APP_IDENTITY"
SAVED_KEYCHAIN_PROFILE="$KEYCHAIN_PROFILE"
CONFIGEOF
echo "  ✓ Configuration saved to $CONFIG_FILE"

echo
echo "Building App..."
echo "────────────────────────────────────────────────"

TOTAL_STEPS=3
if [ -n "$SIGN_APP_IDENTITY" ]; then
    TOTAL_STEPS=8
fi
CURRENT_STEP=0
step() {
    CURRENT_STEP=$((CURRENT_STEP + 1))
    echo "[$CURRENT_STEP/$TOTAL_STEPS] $1"
}

# ---------------------------------------------------------------------------
# Clean
# ---------------------------------------------------------------------------
step "Cleaning build directory..."
rm -rf "$BUILD_DIR"
mkdir -p "$BUILD_DIR"

# ---------------------------------------------------------------------------
# Build (unsigned; signing is done below with the Developer ID identity)
# ---------------------------------------------------------------------------
step "Building $APP_NAME with xcodebuild..."
cd "$SCRIPT_DIR"
if ! xcodebuild -project "$PROJECT" \
    -scheme "$SCHEME" \
    -configuration Release \
    -derivedDataPath "$DERIVED_DIR" \
    build \
    CODE_SIGN_IDENTITY="" \
    CODE_SIGNING_REQUIRED=NO \
    CODE_SIGNING_ALLOWED=NO \
    > "$BUILD_DIR/build.log" 2>&1; then
    echo "Error: Build failed. Last lines of $BUILD_DIR/build.log:"
    tail -n 20 "$BUILD_DIR/build.log"
    exit 1
fi

if [ ! -d "$BUILT_APP" ]; then
    echo "Error: $BUILT_APP not found. Check $BUILD_DIR/build.log"
    exit 1
fi
echo "  ✓ App built successfully"

VERSION=$(/usr/libexec/PlistBuddy -c "Print :CFBundleShortVersionString" "$BUILT_APP/Contents/Info.plist" 2>/dev/null || echo "unknown")
BUILD_NUM=$(/usr/libexec/PlistBuddy -c "Print :CFBundleVersion" "$BUILT_APP/Contents/Info.plist" 2>/dev/null || echo "")

# Stage the app into the output directory
OUTPUT_DIR="$SCRIPT_DIR/dist/$APP_NAME-${VERSION}"
FINAL_APP="$OUTPUT_DIR/$APP_NAME.app"
ZIP_NAME="$APP_NAME-${VERSION}.zip"

step "Staging app..."
rm -rf "$OUTPUT_DIR"
mkdir -p "$OUTPUT_DIR"
ditto "$BUILT_APP" "$FINAL_APP"
echo "  ✓ App copied to $OUTPUT_DIR/"

# ---------------------------------------------------------------------------
# Sign / notarize / staple
# ---------------------------------------------------------------------------
if [ -n "$SIGN_APP_IDENTITY" ]; then
    step "Signing app (hardened runtime)..."

    # Sign nested code first (inside-out via find -d), then the app bundle itself.
    # Avoids --deep, which is deprecated for signing and applies one set of options to everything.
    NESTED_COUNT=0
    while IFS= read -r -d '' nested; do
        codesign --sign "$SIGN_APP_IDENTITY" \
            --force --timestamp --options runtime \
            "$nested" >> "$BUILD_DIR/codesign.log" 2>&1 || {
            echo "Error: Failed to sign $nested. See $BUILD_DIR/codesign.log"
            tail -n 20 "$BUILD_DIR/codesign.log"
            echo
            echo "Common issues:"
            echo "  - Certificate not found. List available: security find-identity -p basic -v"
            echo "  - Identity string doesn't match exactly"
            echo "  - Certificate expired or not trusted"
            exit 1
        }
        NESTED_COUNT=$((NESTED_COUNT + 1))
    done < <(find -d "$FINAL_APP/Contents" \
        \( -name "*.framework" -o -name "*.dylib" -o -name "*.xpc" -o -name "*.appex" -o -name "*.app" \) \
        -print0)
    echo "  ✓ Signed $NESTED_COUNT nested item(s)"

    codesign --sign "$SIGN_APP_IDENTITY" \
        --force --timestamp --options runtime \
        "$FINAL_APP" >> "$BUILD_DIR/codesign.log" 2>&1 || {
        echo "Error: App signing failed. See $BUILD_DIR/codesign.log"
        tail -n 20 "$BUILD_DIR/codesign.log"
        exit 1
    }
    echo "  ✓ App signed"

    step "Verifying signature..."
    if ! codesign --verify --deep --strict --verbose=2 "$FINAL_APP" >> "$BUILD_DIR/codesign.log" 2>&1; then
        echo "Error: Signature verification failed. See $BUILD_DIR/codesign.log"
        tail -n 20 "$BUILD_DIR/codesign.log"
        exit 1
    fi
    echo "  ✓ Signature verified"

    step "Creating archive for notarization..."
    NOTARY_ZIP="$BUILD_DIR/$APP_NAME-notarize.zip"
    ditto -c -k --keepParent "$FINAL_APP" "$NOTARY_ZIP"
    echo "  ✓ Archive created"

    step "Submitting app for notarization..."
    echo "  (This may take several minutes...)"
    if ! xcrun notarytool submit "$NOTARY_ZIP" \
        --keychain-profile "$KEYCHAIN_PROFILE" \
        --wait \
        > "$BUILD_DIR/notarize_app.log" 2>&1; then
        echo "Error: Notarization submission failed. Check $BUILD_DIR/notarize_app.log"
        echo "       Make sure keychain profile '$KEYCHAIN_PROFILE' exists."
        echo "       Run: xcrun notarytool store-credentials $KEYCHAIN_PROFILE --apple-id <email> --team-id <team>"
        exit 1
    fi

    # notarytool exits 0 even when the submission is rejected, so check the status
    if ! grep -q "status: Accepted" "$BUILD_DIR/notarize_app.log"; then
        echo "Error: Notarization was not accepted."
        cat "$BUILD_DIR/notarize_app.log"
        SUBMISSION_ID=$(grep -m1 "id:" "$BUILD_DIR/notarize_app.log" | awk '{print $2}')
        if [ -n "$SUBMISSION_ID" ]; then
            echo
            echo "Details: xcrun notarytool log $SUBMISSION_ID --keychain-profile $KEYCHAIN_PROFILE"
        fi
        exit 1
    fi
    echo "  ✓ App notarized"

    step "Stapling notarization ticket..."
    if xcrun stapler staple "$FINAL_APP" > "$BUILD_DIR/staple_app.log" 2>&1; then
        echo "  ✓ Notarization ticket stapled"
    else
        echo "Warning: Stapling failed, but notarization succeeded. App will validate online."
        echo "         Check $BUILD_DIR/staple_app.log for details"
    fi
fi

# ---------------------------------------------------------------------------
# Package the final app into a zip (created after stapling so the ticket is included)
# ---------------------------------------------------------------------------
step "Creating distributable zip..."
ditto -c -k --keepParent "$FINAL_APP" "$OUTPUT_DIR/$ZIP_NAME"
ZIP_SIZE=$(du -h "$OUTPUT_DIR/$ZIP_NAME" | cut -f1)
echo "  ✓ Created $OUTPUT_DIR/$ZIP_NAME"

# ---------------------------------------------------------------------------
# Summary
# ---------------------------------------------------------------------------
echo
echo "╔════════════════════════════════════════════════╗"
echo "║   Build Complete!                              ║"
echo "╚════════════════════════════════════════════════╝"
echo
echo "App Details:"
echo "  Name:        $APP_NAME.app"
echo "  Version:     $VERSION${BUILD_NUM:+ ($BUILD_NUM)}"
echo "  Directory:   $OUTPUT_DIR"
echo "  Zip:         $ZIP_NAME ($ZIP_SIZE)"
echo
if [ -n "$SIGN_APP_IDENTITY" ]; then
    echo "Signing & Notarization:"
    echo "  Status:           Signed and Notarized"
    echo "  App Identity:     $SIGN_APP_IDENTITY"
    echo "  Keychain Profile: $KEYCHAIN_PROFILE"
    echo
    echo "Verification:"
    echo "  codesign --verify --deep --strict --verbose=2 \"$FINAL_APP\""
    echo "  spctl --assess --type execute --verbose \"$FINAL_APP\""
    echo "  xcrun stapler validate \"$FINAL_APP\""
else
    echo "Signing: Disabled (development build - app is NOT signed or notarized)"
fi
echo

read -p "Clean up build artifacts? [Y/n]: " CLEANUP
if [[ "$CLEANUP" =~ ^[Yy]?$ ]]; then
    rm -rf "$BUILD_DIR"
    echo "✓ Build directory cleaned"
fi

echo
echo "Done!"
echo
